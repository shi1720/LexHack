import type { RiskTier, SystemProfile } from '../types.js';
import { buildSnapshot } from '../ingest/snapshot.js';
import { scan } from '../scan.js';
import { BENCHMARK, type BenchmarkCase } from './corpus.js';

export { BENCHMARK } from './corpus.js';
export type { BenchmarkCase } from './corpus.js';

export interface CaseOutcome {
  id: string;
  description: string;
  expectedTier: RiskTier;
  actualTier: RiskTier;
  tierCorrect: boolean;
  missedFindings: string[];
  falseFindings: string[];
  rationale: string;
}

export interface BenchmarkSummary {
  total: number;
  tierCorrect: number;
  tierAccuracy: number;
  expectedFindings: number;
  recalledFindings: number;
  recall: number;
  forbiddenChecks: number;
  forbiddenViolations: number;
  carveOutPrecision: number;
  outcomes: CaseOutcome[];
  durationMs: number;
}

function runCase(bench: BenchmarkCase): CaseOutcome {
  const snapshot = buildSnapshot({
    name: bench.id,
    files: Object.entries(bench.files).map(([path, bytes]) => ({ path, bytes })),
  });
  const profile: Partial<SystemProfile> = {
    name: bench.id,
    purpose: bench.description,
    markets: ['eu', 'us-nyc', 'us-co', 'us-federal'],
    ...bench.profile,
  };
  const report = scan(snapshot, { profile });
  const found = new Set(report.classification.findings.map((f) => f.id));

  return {
    id: bench.id,
    description: bench.description,
    expectedTier: bench.tier,
    actualTier: report.classification.tier,
    tierCorrect: report.classification.tier === bench.tier,
    missedFindings: (bench.expectFindings ?? []).filter((f) => !found.has(f)),
    falseFindings: (bench.forbidFindings ?? []).filter((f) => found.has(f)),
    rationale: bench.rationale,
  };
}

/**
 * Run the labelled corpus and report the numbers, including the cases Annex
 * gets wrong. Exposed as a library function and as `annex benchmark` so the
 * figures in the README are never typed by hand.
 */
export function runBenchmark(): BenchmarkSummary {
  const started = Date.now();
  const outcomes = BENCHMARK.map(runCase);
  const expectedFindings = BENCHMARK.reduce((n, b) => n + (b.expectFindings?.length ?? 0), 0);
  const missed = outcomes.reduce((n, o) => n + o.missedFindings.length, 0);
  const forbiddenChecks = BENCHMARK.reduce((n, b) => n + (b.forbidFindings?.length ?? 0), 0);
  const violations = outcomes.reduce((n, o) => n + o.falseFindings.length, 0);
  const tierCorrect = outcomes.filter((o) => o.tierCorrect).length;

  return {
    total: outcomes.length,
    tierCorrect,
    tierAccuracy: tierCorrect / outcomes.length,
    expectedFindings,
    recalledFindings: expectedFindings - missed,
    recall: expectedFindings === 0 ? 1 : (expectedFindings - missed) / expectedFindings,
    forbiddenChecks,
    forbiddenViolations: violations,
    carveOutPrecision: forbiddenChecks === 0 ? 1 : (forbiddenChecks - violations) / forbiddenChecks,
    outcomes,
    durationMs: Date.now() - started,
  };
}

const pct = (n: number) => `${(n * 100).toFixed(1)}%`;

/** Markdown report, written to docs/BENCHMARK.md by `npm run benchmark`. */
export function benchmarkMarkdown(summary: BenchmarkSummary): string {
  const wrong = summary.outcomes.filter((o) => !o.tierCorrect || o.missedFindings.length || o.falseFindings.length);

  return [
    '# Benchmark',
    '',
    '> Generated by `npm run benchmark:report`. Do not edit by hand — the numbers',
    '> below come straight out of the engine, including the cases it gets wrong.',
    '',
    'Annex is a classifier, so it owes you its error rate.',
    '',
    'The corpus is hand-labelled: each case is a miniature repository plus the',
    'classification a competent reader of the Act would give it, and the reason.',
    'Roughly half the corpus exists to catch **false positives** — systems that look',
    'like an Annex III use case to a keyword matcher but are expressly carved out of',
    'it, plus a documentation site that merely *writes about* prohibited practices.',
    '',
    '## Results',
    '',
    '| Metric | Result | What it measures |',
    '|---|---|---|',
    `| Risk-tier accuracy | **${pct(summary.tierAccuracy)}** (${summary.tierCorrect}/${summary.total}) | The tier Annex assigns matches the label |`,
    `| Finding recall | **${pct(summary.recall)}** (${summary.recalledFindings}/${summary.expectedFindings}) | Classification findings a competent reader would make, that Annex makes |`,
    `| Carve-out precision | **${pct(summary.carveOutPrecision)}** (${summary.forbiddenChecks - summary.forbiddenViolations}/${summary.forbiddenChecks}) | Findings the statute expressly excludes, that Annex correctly does not make |`,
    `| Runtime | ${summary.durationMs} ms | The whole corpus, single-threaded, no network |`,
    '',
    '## Cases Annex gets wrong',
    '',
    wrong.length === 0
      ? [
          'None in the current corpus.',
          '',
          'That is a statement about the corpus, not about the world. Every case here',
          'was written by the same people who wrote the detectors, which is the standard',
          'weakness of a self-authored benchmark: it measures whether the engine still',
          'does what it was built to do, and it cannot measure what nobody thought to',
          'test. The cases most likely to break it are the ones the honest-limits',
          'section of the README names — an in-house ML platform with bespoke naming, a',
          'regulated decision expressed in a language the detector corpus barely covers,',
          'and any obligation whose answer is a judgement rather than a fact about code.',
        ].join('\n')
      : wrong
          .map((o) =>
            [
              `### \`${o.id}\` — ${o.description}`,
              '',
              `Expected **${o.expectedTier}**, produced **${o.actualTier}**.`,
              o.missedFindings.length ? `Missed: ${o.missedFindings.map((f) => `\`${f}\``).join(', ')}.` : '',
              o.falseFindings.length ? `False: ${o.falseFindings.map((f) => `\`${f}\``).join(', ')}.` : '',
              '',
              `_Label rationale:_ ${o.rationale}`,
            ]
              .filter(Boolean)
              .join('\n'),
          )
          .join('\n\n'),
    '',
    '## The full corpus',
    '',
    '| Case | Expected | Produced | |',
    '|---|---|---|---|',
    ...summary.outcomes.map(
      (o) =>
        `| \`${o.id}\` — ${o.description} | ${o.expectedTier} | ${o.actualTier} | ${o.tierCorrect && !o.missedFindings.length && !o.falseFindings.length ? '✓' : '✗'} |`,
    ),
    '',
    '## What this does not measure',
    '',
    '- **Control-level accuracy on real repositories.** The corpus cases are small by',
    '  design, so each isolates one legal question. Golden fixtures on individual',
    '  controls (`npm test`) cover detector behaviour; neither is a substitute for',
    '  running Annex on a large production codebase, which is the next thing to do.',
    '- **Whether a conformity assessor would accept the output.** That is a question',
    '  about institutions, not code, and it is answered by showing dossiers to',
    '  notified bodies rather than by a benchmark.',
    '- **Anything about the quality of the law.** Annex reports what the statute says.',
    '',
  ].join('\n');
}
